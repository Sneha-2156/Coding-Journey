package day01;
// Positive , Negative or Zero
/* n > 0 -> positie ; n < 0 -> Negative ; n =0 -> Zero */
public class p2 {
    void main(){
        int n = 9;
        if( n > 0){
            System.out.println("Positie");
        }else if(n < 0){
            System.out.println("Negative");
        }else{
            System.out.println("Zero");
        }
    }
}
